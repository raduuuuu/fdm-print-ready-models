# What PrusaSlicer 2.9.4 printed for a part with a 40 mm bridge (recorded on the CI machine).
RECORDED = """10 => Processing triangulated mesh
20 => Generating perimeters
30 => Preparing infill
45 => Making infill
65 => Searching support spots
69 => Alert if supports needed
print warning: Detected print stability issues:
bridge40.stl
Floating bridge anchors, Low bed adhesion, Loose extrusions, Long bridging extrusions
Consider enabling supports.
Also consider enabling brim.
89 => Calculating overhanging perimeters
88 => Generating skirt and brim
90 => Exporting G-code to bridge40.gcode
Slicing result exported to bridge40.gcode
"""
CLEAN = "10 => Processing triangulated mesh\n90 => Exporting G-code to clean.gcode\nSlicing result exported to clean.gcode\n"


def box(x0, x1, y0, y1, z0, z1):
    return Manifold.cube([x1 - x0, y1 - y0, z1 - z0]).translate([x0, y0, z0])


def stl(tmp_path, solid, name="part.stl"):
    mesh = solid.to_mesh()
    path = tmp_path / name
    trimesh.Trimesh(np.asarray(mesh.vert_properties)[:, :3], np.asarray(mesh.tri_verts), process=False).export(path)
    return str(path)


def bridge(gap):
    return box(0, 4, 0, 20, 0, 10) + box(4 + gap, 8 + gap, 0, 20, 0, 10) + box(0, 8 + gap, 0, 20, 10, 12)


LEDGE = box(0, 20, 0, 20, 0, 10) + box(0, 30, 0, 20, 10, 12)


def test_alerts_are_read_from_recorded_output():
    assert slicer.parse_alerts(RECORDED) == ["Floating bridge anchors", "Long bridging extrusions",
                                              "Loose extrusions", "Low bed adhesion"]
    assert slicer.parse_alerts(CLEAN) == []


def gcode(tmp_path, body, header="; generated by PrusaSlicer 2.9.4 on 2026-11-25 at 13:24:10 UTC"):
    p = tmp_path / "out.gcode"
    p.write_text(header + "\n" + body)
    return str(p)


PRUSA_BODY = """;LAYER_CHANGE
;Z:0.2
;TYPE:External perimeter
G1 X104 Y118
G1 X152 Y118 E1
G1 X152 Y138 E1
G1 X104 Y138 E1
G1 X104 Y118 E1
;LAYER_CHANGE
;Z:10.2
;TYPE:Bridge infill
G1 X108 Y128
G1 X148 Y128 E2
"""
ORCA_BODY = """; CHANGE_LAYER
; Z_HEIGHT: 0.2
; FEATURE: Outer wall
G1 X104 Y118
G1 X152 Y118 E1
G1 X152 Y138 E1
G1 X104 Y138 E1
G1 X104 Y118 E1
; CHANGE_LAYER
; Z_HEIGHT: 10.2
; FEATURE: Bridge
G1 X108 Y128
G1 X148 Y128 E2
"""


@pytest.mark.parametrize("body, header, name", [
    (PRUSA_BODY, "; generated by PrusaSlicer 2.9.4 on 2026-11-25 at 13:24:10 UTC", "PrusaSlicer"),
    (ORCA_BODY, "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.1 on 2026-11-25 at 14:23:24", "OrcaSlicer"),
])
def test_both_gcode_dialects_are_read_and_measured(tmp_path, body, header, name):
    found, version, segs = slicer.parse_gcode(gcode(tmp_path, body, header))
    assert found == name and version[:3] in ("2.9", "2.5") and len(segs) == 5
    spans, walls = slicer.measure(bridge(40.0), segs)
    assert len(spans) == 1 and spans[0][0] == pytest.approx(39.0, abs=1.1)     # the 40 mm gap, less the lean on each side
    assert spans[0][1:] == (pytest.approx(24.0, abs=0.6), pytest.approx(10.0, abs=0.6), 10.2)   # in part coordinates
    assert walls == []


@pytest.mark.parametrize("content, message", [
    (None, "no G-code was written"),
    ("; generated by PrusaSlicer 2.9.4\n", "no layers"),
    ("G1 X1 Y1 E1\n", "no slicer header"),
    ("; generated by PrusaSlicer 2.9.4\n;LAYER_CHANGE\n;Z:0.2\nM82\n", "absolute extrusion"),
])
def test_a_slice_that_cannot_be_trusted_is_an_error(tmp_path, content, message):
    path = str(tmp_path / "x.gcode")
    if content is not None:
        open(path, "w").write(content)
    with pytest.raises(slicer.SlicerError, match=message):
        slicer.parse_gcode(path)


# ---- a stand-in slicer, to test the whole path without a real one

def stand_in(tmp_path, mode="ok", body=PRUSA_BODY, out_text=RECORDED):
    """An executable that behaves like prusa-slicer for one run."""
    path = tmp_path / "prusa-slicer"
    path.write_text(f"""#!{sys.executable}
import sys, time
mode = {mode!r}
if mode == "slow":
    time.sleep(30)
if mode == "fail":
    sys.stderr.write("something went wrong\\n"); sys.exit(3)
out = sys.argv[sys.argv.index("-o") + 1]
assert sys.argv[-1].startswith("/"), "the part must be passed as an absolute path"
if mode != "nothing":
    open(out, "w").write("; generated by PrusaSlicer 2.9.4 on a test\\n" + {body!r})
sys.stdout.write({out_text!r})
""")
    path.chmod(path.stat().st_mode | stat.S_IEXEC)
    return str(path)


def run(args, capsys):
    code = check.main(args)
    return code, capsys.readouterr().out


def test_without_a_slicer_the_verdict_says_geometry_only(tmp_path, capsys):
    code, out = run([stl(tmp_path, box(0, 30, 0, 20, 0, 10)), "--no-report"], capsys)
    assert code == 0 and "the slicer check did not run: no slicer found" in out
    assert "geometry only: the slicer check did not run" in out


def test_the_slicer_check_can_be_switched_off(tmp_path, capsys):
    code, out = run([stl(tmp_path, box(0, 30, 0, 20, 0, 10)), "--no-report", "--slicer", "none"], capsys)
    assert code == 0 and "the slicer check did not run: the slicer check was switched off" in out


def test_a_long_bridge_found_by_the_slicer_fails(tmp_path, capsys):
    p = stl(tmp_path, bridge(40.0))
    code, out = run([p, "--slicer-path", stand_in(tmp_path)], capsys)
    assert code == 1
    assert "FAIL  Slicer: bridging line over air longer than the hard limit: span 39" in out
    assert "warn  Slicer alert: Long bridging extrusions" in out
    assert "sliced with PrusaSlicer 2.9.4" in out and "geometry only" not in out
    r = json.load(open(tmp_path / "part.report.json"))
    assert r["slicer"] == {"name": "PrusaSlicer", "version": "2.9.4"}


def test_all_seven_checks_ran_reads_as_a_plain_pass(tmp_path, capsys):
    body = PRUSA_BODY.split(";LAYER_CHANGE\n;Z:10.2")[0]
    part = box(0, 48, 0, 20, 0, 10)
    code, out = run([stl(tmp_path, part), "--no-report", "--slicer-path", stand_in(tmp_path, body=body, out_text=CLEAN)], capsys)
    assert code == 0 and out.strip().endswith("VERDICT: PASS")


@pytest.mark.parametrize("mode, message", [
    ("fail", "the slicer exited with code 3: something went wrong"),
    ("nothing", "could not confirm the slice ran"),
])
def test_a_failed_slicer_run_is_incomplete_not_a_pass(tmp_path, capsys, mode, message):
    code, out = run([stl(tmp_path, box(0, 48, 0, 20, 0, 10)), "--no-report", "--slicer-path", stand_in(tmp_path, mode)], capsys)
    assert code == 2 and "VERDICT: INCOMPLETE (crashed: slicer)" in out and message in out


def test_a_slicer_that_hangs_is_stopped(tmp_path, capsys, monkeypatch):
    monkeypatch.setitem(limits._TESTED_CONSTANTS, "SLICER_TIMEOUT", 1)    # the runner resets limits per run
    code, out = run([stl(tmp_path, box(0, 48, 0, 20, 0, 10)), "--no-report", "--slicer-path", stand_in(tmp_path, "slow")], capsys)
    assert code == 2 and "did not finish within 1 seconds" in out


def test_an_untested_slicer_version_warns(tmp_path, capsys):
    body = PRUSA_BODY.split(";LAYER_CHANGE\n;Z:10.2")[0]
    exe = stand_in(tmp_path, body=body, out_text=CLEAN)
    script = open(exe).read().replace("PrusaSlicer 2.9.4", "PrusaSlicer 3.4.0")
    open(exe, "w").write(script)
    code, out = run([stl(tmp_path, box(0, 48, 0, 20, 0, 10)), "--no-report", "--slicer-path", exe], capsys)
    assert code == 0 and "warn  Slicer version this check was not tested with: PrusaSlicer 3.4.0" in out


def test_orca_without_presets_is_skipped_with_the_reason(tmp_path, capsys):
    exe = stand_in(tmp_path)
    code, out = run([stl(tmp_path, box(0, 30, 0, 20, 0, 10)), "--no-report", "--slicer", "orca", "--slicer-path", exe], capsys)
    assert code == 0 and "OrcaSlicer needs --orca-presets" in out


# ---- real slicers

prusa = shutil.which("prusa-slicer")
orca_presets = os.environ.get("FDM_ORCA_PRESETS")       # "machine.json;process.json;filament.json"


@pytest.mark.live_slicer
@pytest.mark.skipif(not prusa, reason="prusa-slicer is not installed")
def test_live_prusaslicer_reports_the_long_bridge(tmp_path):
    info = {}
    part = bridge(40.0)
    found = slicer.run(part, stl(tmp_path, part), want="prusa", info=info)
    assert info["name"] == "PrusaSlicer"
    assert "Long bridging extrusions" in {f.value for f in found if f.kind == "slicer_alert"}
    long_bridge = [f for f in found if f.kind == "slicer_bridge_too_long"]
    assert len(long_bridge) == 1 and 35 <= long_bridge[0].value <= 41


@pytest.mark.live_slicer
@pytest.mark.skipif(not prusa, reason="prusa-slicer is not installed")
def test_live_prusaslicer_passes_a_plain_block(tmp_path):
    part = box(0, 30, 0, 20, 0, 10)
    found = slicer.run(part, stl(tmp_path, part), want="prusa")
    assert [f for f in found if limits.KINDS[f.kind]["severity"] == "fail"] == []
    assert [f.value for f in found if f.kind == "slicer_alert"] == []


@pytest.mark.live_slicer
@pytest.mark.skipif(not prusa, reason="prusa-slicer is not installed")
def test_live_a_flat_ledge_still_fails_although_the_slicer_measure_misses_it(tmp_path, capsys):
    """Known gap: the wall a slicer prints around a flat ledge is held at both ends, so the
    slicer measurement reads it as a bridge. The layer check is what fails the part."""
    code, out = run([stl(tmp_path, LEDGE), "--no-report", "--slicer", "prusa"], capsys)
    assert code == 1 and "FAIL  Flat underside sticking out too far" in out
    assert "sliced with PrusaSlicer" in out and "FAIL  Slicer" not in out


@pytest.mark.live_slicer
@pytest.mark.skipif(not (orca_presets and slicer.find("orca")), reason="OrcaSlicer or FDM_ORCA_PRESETS not available")
def test_live_orcaslicer_reports_the_long_bridge(tmp_path):
    info = {}
    part = bridge(40.0)
    found = slicer.run(part, stl(tmp_path, part), want="orca", orca_presets=orca_presets.split(";"), info=info)
    assert info["name"] == "OrcaSlicer"
    assert any(f.kind == "slicer_bridge_too_long" and 35 <= f.value <= 41 for f in found)
    assert any(f.kind == "slicer_alerts_not_read" for f in found)
