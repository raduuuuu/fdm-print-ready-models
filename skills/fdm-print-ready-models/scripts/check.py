"""Run the print-readiness checks on one or more STL files and give one verdict per part.

    check.py part.stl [more.stl ...]      text report, <part>.report.json next to each STL
    check.py part.stl --out report.json   choose the report path (one part only)
    check.py part.stl --no-report         do not write a report file
    check.py part.stl --verbose           also list findings that are information only
    check.py --skill-tables               print the tables SKILL.md must contain
    check.py --update-skill-tables        rewrite those tables in ../SKILL.md

The part must be an STL in print orientation: flat side on the bed, z up, sizes in mm.
Checked for a 0.4 mm nozzle and 0.2 mm layers.

Verdict and exit code:
    FAIL        1   at least one finding that makes the part not print-ready
    INCOMPLETE  2   the part could not be read, or a check crashed, so there is no full answer
    PASS        0   nothing failed. The verdict line names any warnings and any check that did
                    not run; a pass never hides either.
A failure outranks an incomplete run: FAIL is reported even if another check crashed.

This file owns the verdict and the report. The checks only measure (layers.py); limits.py owns
the numbers, how serious each kind of finding is and whether it may be waived.
"""
import argparse
import datetime
import hashlib
import json
import os
import platform
import sys
import traceback

__version__ = "0.1.0"
REPORT_SCHEMA = 1
HERE = os.path.dirname(os.path.abspath(__file__))
NEEDS = ("numpy", "trimesh", "manifold3d")

BEGIN = "<!-- generated by check.py --update-skill-tables: do not edit by hand -->"
END = "<!-- end of generated tables -->"


def missing_packages(names=NEEDS):
    import importlib.util
    return [n for n in names if importlib.util.find_spec(n) is None]


def install_help(missing):
    req = os.path.join(HERE, "requirements.txt")
    me = os.path.join(HERE, "check.py")
    return (f"Missing Python packages: {', '.join(missing)}.\n"
            f"Run the checks with uv, which installs the pinned packages in a private environment:\n"
            f"    uv run --no-project --python 3.12 --with-requirements \"{req}\" \"{me}\" part.stl\n"
            f"or, without uv:\n"
            f"    python3 -m venv .venv && .venv/bin/pip install -r \"{req}\"\n"
            f"    .venv/bin/python \"{me}\" part.stl")


# The checks this tool knows about, in the order SKILL.md describes them. `run` is None for a
# check that has not shipped yet; such a check is named on every verdict line.
def _run_layers(solid):
    import layers
    return layers.run(solid)


CHECKS = [
    {"name": "layer", "run": _run_layers,
     "text": "Thin features, floating regions, flat ledges and bridges, layer by layer"},
    {"name": "post", "run": None, "text": "Overhangs carried only by thin posts; slender columns"},
    {"name": "slope", "run": None, "text": "Top surfaces between 3 and 35 degrees"},
    {"name": "overhang angle", "run": None, "text": "Undersides flatter than 45 degrees"},
    {"name": "corner", "run": None, "text": "Sharp inner corners (report only)"},
    {"name": "support", "run": None, "text": "Where supports would go, and whether they can be removed"},
    {"name": "slicer", "run": None, "text": "A real slicer run: its alerts, bridges and overhang walls"},
]


def decide(check_results, part_error=None):
    """The verdict for one part. `check_results` is a list of {"name", "status"} with status in
    pass | warn | fail | error | not_shipped | skipped. Returns (verdict, qualifiers)."""
    statuses = [c["status"] for c in check_results]
    if "fail" in statuses:
        verdict = "FAIL"
    elif part_error or "error" in statuses:
        verdict = "INCOMPLETE"
    else:
        verdict = "PASS"
    quals = []
    crashed = [c["name"] for c in check_results if c["status"] == "error"]
    if crashed and not part_error:
        quals.append("crashed: " + ", ".join(crashed))
    skipped = [c["name"] for c in check_results if c["status"] == "skipped"]
    if skipped:
        quals.append("skipped: " + ", ".join(skipped))
    not_run = [c["name"] for c in check_results if c["status"] == "not_shipped"]
    if not_run:
        quals.append("checks not run: " + ", ".join(not_run))
    return verdict, quals


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _versions():
    import importlib.metadata as md
    out = {"python": platform.python_version()}
    for n in NEEDS:
        try:
            out[n] = md.version(n)
        except md.PackageNotFoundError:
            out[n] = "unknown"
    return out


def _finding_dict(f):
    import limits as L
    d = f.to_dict()
    k = L.KINDS[f.kind]
    d["severity"] = k["severity"]
    d["waivable"] = k["waivable"]
    d["limit"] = None if k["limit"] is None else L.value(k["limit"])
    return d


def inspect_part(path):
    """Everything known about one part, as the report dict. Never raises for a bad part."""
    import limits as L
    report = {
        "schema": REPORT_SCHEMA,
        "tool": {"name": "fdm-print-ready-models", "version": __version__},
        "generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "part": {"file": os.path.basename(path)},
        "setup": {"nozzle_mm": L.NOZZLE, "layer_mm": L.LAYER},
        "limits": {n: {"value": lim.value, "unit": lim.unit, "source": lim.source}
                   for n, lim in L.LIMITS.items()},
        "versions": _versions(),
        "checks": [], "part_error": None, "part_findings": [],
    }

    solid = None
    if not os.path.isfile(path):
        report["part_error"] = f"file not found: {os.path.basename(path)}"
    else:
        report["part"]["sha256"] = _sha256(path)
        import layers
        try:
            solid = layers.load(path)
        except layers.MeshError as e:
            report["part_error"] = f"mesh problem: {e}"
        except Exception as e:  # the STL reader raises many types; all mean "cannot read this"
            report["part_error"] = f"not a readable STL ({type(e).__name__}: {e})"

    if solid is not None:
        bb = solid.bounding_box()
        size = [round(bb[3] - bb[0], 2), round(bb[4] - bb[1], 2), round(bb[5] - bb[2], 2)]
        report["part"].update({"size_mm": size, "z_min": round(bb[2], 3),
                               "bodies": len(solid.decompose())})
        biggest = max(size)
        if biggest < L.MIN_PART_SIZE or biggest > L.MAX_PART_SIZE or size[2] < L.LAYER:
            report["part_error"] = (f"implausible size {size[0]} x {size[1]} x {size[2]} mm: "
                                    "check the export units (mm) and the orientation")
            solid = None
        else:
            if biggest < L.SMALL_PART_SIZE:
                report["part_findings"].append(
                    {"kind": "small_part", "value": biggest, "what": "size_mm", "severity": "warn",
                     "waivable": True, "limit": L.SMALL_PART_SIZE})
            if abs(bb[2]) > L.BED_TOL:
                report["part_findings"].append(
                    {"kind": "off_bed", "value": round(bb[2], 3), "what": "z_min_mm",
                     "severity": "warn", "waivable": True, "limit": 0.0})

    for c in CHECKS:
        entry = {"name": c["name"], "status": "not_shipped", "findings": [], "error": None}
        if c["run"] is not None and solid is None:
            entry["status"] = "error"
            entry["error"] = "not run: the part could not be read"
        elif c["run"] is not None:
            try:
                entry["findings"] = [_finding_dict(f) for f in c["run"](solid)]
                sev = {f["severity"] for f in entry["findings"]}
                entry["status"] = "fail" if "fail" in sev else "warn" if "warn" in sev else "pass"
            except Exception:  # one crashing check must not hide the others; it is reported
                entry["status"] = "error"
                entry["error"] = traceback.format_exc()
        report["checks"].append(entry)

    verdict, quals = decide(report["checks"], report["part_error"])
    every = report["part_findings"] + [f for c in report["checks"] for f in c["findings"]]
    counts = {s: sum(1 for f in every if f["severity"] == s) for s in ("fail", "warn", "info")}
    if counts["warn"]:
        quals.insert(0, f"with {counts['warn']} warning{'s' if counts['warn'] != 1 else ''}")
    ran = [c["name"] for c in report["checks"] if c["status"] in ("pass", "warn", "fail")]
    if verdict == "PASS" and len(ran) < len(CHECKS):
        quals.insert(0, f"{' and '.join(ran)} check only" if ran else "no check ran")
    report.update({"verdict": verdict, "qualifiers": quals, "counts": counts})
    return report


def _describe(f):
    import limits as L
    text = L.KINDS[f["kind"]]["text"]
    what = {"span_mm": "span {v} mm", "reach_mm": "sticks out {v} mm", "area_mm2": "area {v} mm2",
            "size_mm": "largest side {v} mm", "z_min_mm": "lowest point at z = {v} mm"}[f["what"]]
    line = f"{text}: {what.format(v=f['value'])}"
    if f.get("width"):
        line += f", {f['width']} mm wide"
    if f.get("limit") is not None and f["what"] in ("span_mm", "reach_mm"):
        line += f" (limit {f['limit']} mm)"
    if "x" in f:
        z = f"{f['z0']}" if f["z0"] == f["z1"] else f"{f['z0']} to {f['z1']}"
        line += f"  at x {f['x']}, y {f['y']}, z {z}"
    return line


def format_text(report, verbose=False):
    lines = [report["part"]["file"]]
    if report["part_error"]:
        lines.append(f"  could not check this part: {report['part_error']}")
    every = report["part_findings"] + [f for c in report["checks"] for f in c["findings"]]
    for sev, label in (("fail", "FAIL"), ("warn", "warn")):
        for f in every:
            if f["severity"] == sev:
                lines.append(f"  {label}  {_describe(f)}")
    info = [f for f in every if f["severity"] == "info"]
    if info and verbose:
        lines += [f"  info  {_describe(f)}" for f in info]
    elif info:
        longest = max((f["value"] for f in info if f["what"] == "span_mm"), default=None)
        note = f" (longest {longest} mm)" if longest is not None else ""
        lines.append(f"  info  {len(info)} bridge{'s' if len(info) != 1 else ''} within limits{note}; --verbose lists them")
    for c in report["checks"]:
        if c["status"] == "error" and c["error"] and not report["part_error"]:
            lines.append(f"  the {c['name']} check crashed: {c['error'].strip().splitlines()[-1]}")
    tail = f" ({'; '.join(report['qualifiers'])})" if report["qualifiers"] else ""
    lines.append(f"VERDICT: {report['verdict']}{tail}")
    return "\n".join(lines)


def skill_tables():
    """The tables SKILL.md must contain, generated so the text cannot disagree with the code."""
    import limits as L
    out = [BEGIN, "", "### Limits the checks use", "",
           f"For a {L.NOZZLE} mm nozzle and {L.LAYER} mm layers.", "",
           "| Limit | Value | Source | Meaning |", "|---|---|---|---|"]
    for name, lim in L.LIMITS.items():
        out.append(f"| `{name}` | {lim.value:g} {lim.unit} | {lim.source} | {lim.text} |")
    out += ["", "### What the checks report", "",
            "| Finding | Severity | Can be waived | Meaning |", "|---|---|---|---|"]
    for kind, k in L.KINDS.items():
        out.append(f"| `{kind}` | {k['severity']} | {'yes' if k['waivable'] else 'no'} | {k['text']} |")
    out += ["", f"### Checks in version {__version__}", "",
            "| Check | Runs in this version | What it looks at |", "|---|---|---|"]
    for c in CHECKS:
        out.append(f"| {c['name']} | {'yes' if c['run'] is not None else 'no, manual for now'} | {c['text']} |")
    out += ["", END]
    return "\n".join(out)


def update_skill_tables(skill_path):
    with open(skill_path) as fh:
        text = fh.read()
    block = skill_tables()
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n## Reference tables\n\n" + block + "\n"
    with open(skill_path, "w") as fh:
        fh.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Print-readiness checks for FDM parts (STL, print orientation, mm).")
    ap.add_argument("parts", nargs="*", help="STL files")
    ap.add_argument("--out", help="report path (one part only)")
    ap.add_argument("--no-report", action="store_true", help="do not write report files")
    ap.add_argument("--verbose", action="store_true", help="list findings that are information only")
    ap.add_argument("--skill-tables", action="store_true", help="print the tables for SKILL.md")
    ap.add_argument("--update-skill-tables", action="store_true", help="rewrite the tables in ../SKILL.md")
    ap.add_argument("--version", action="version", version=__version__)
    args = ap.parse_args(argv)

    if args.skill_tables:
        print(skill_tables())
        return 0
    if args.update_skill_tables:
        update_skill_tables(os.path.join(os.path.dirname(HERE), "SKILL.md"))
        return 0
    if not args.parts:
        ap.print_usage(sys.stderr)
        return 2
    if args.out and len(args.parts) > 1:
        print("--out takes one part; without it each part gets <part>.report.json", file=sys.stderr)
        return 2
    missing = missing_packages()
    if missing:
        print(install_help(missing), file=sys.stderr)
        return 2

    verdicts = []
    for i, path in enumerate(args.parts):
        report = inspect_part(path)
        verdicts.append(report["verdict"])
        if i:
            print()
        print(format_text(report, args.verbose))
        if not args.no_report:
            out = args.out or os.path.splitext(path)[0] + ".report.json"
            try:
                with open(out, "w") as fh:
                    json.dump(report, fh, indent=1)
                print(f"report: {out}")
            except OSError as e:
                print(f"warning: could not write the report ({e})", file=sys.stderr)
    return 1 if "FAIL" in verdicts else 2 if "INCOMPLETE" in verdicts else 0


if __name__ == "__main__":
    sys.path.insert(0, HERE)
    sys.exit(main())
