def decide(check_results, part_error=None):
    """The verdict for one part. `check_results` is a list of {"name", "status"} with status in
    pass | warn | fail | error | not_shipped | skipped. Returns (verdict, qualifiers)."""
    statuses = [c["status"] for c in check_results]
    if "fail" in statuses:
        verdict = "FAIL"
    elif part_error or "error" in statuses:
        verdict = "INCOMPLETE"
    else:
        verdict = "PASS"
    quals = []
    crashed = [c["name"] for c in check_results if c["status"] == "error"]
    if crashed and not part_error:
        quals.append("crashed: " + ", ".join(crashed))
    skipped = [c["name"] for c in check_results if c["status"] == "skipped"]
    if skipped:
        quals.append("geometry only: the " + ", ".join(skipped) + " check did not run")
    not_run = [c["name"] for c in check_results if c["status"] == "not_shipped"]
    if not_run:
        quals.append("checks not run: " + ", ".join(not_run))
    return verdict, quals


def load_exceptions(path):
    """Read an exceptions file. Returns a list of {"kind", "box", "reason"}.
    Raises ValueError with a message a person can act on when the file is not usable."""
    import limits as L
    try:
        with open(path) as fh:
            data = json.load(fh)
    except json.JSONDecodeError as e:
        raise ValueError(f"not valid JSON at line {e.lineno}, column {e.colno}: {e.msg}")
    except OSError as e:
        raise ValueError(f"cannot be read ({e.strerror})")
    if not isinstance(data, dict) or not isinstance(data.get("exceptions"), list):
        raise ValueError('must be an object with a list named "exceptions"')
    out = []
    for n, e in enumerate(data["exceptions"], 1):
        where = f"entry {n}"
        if not isinstance(e, dict):
            raise ValueError(f"{where} must be an object with kind, box and reason")
        kind = e.get("kind")
        if kind not in L.KINDS:
            raise ValueError(f"{where}: unknown kind {kind!r}; the kinds are listed in SKILL.md")
        reason = e.get("reason")
        if not isinstance(reason, str) or len(reason.strip()) < 5:
            raise ValueError(f"{where}: a reason is required (say why the feature is intended)")
        box = e.get("box")
        if box is not None:
            ok = (isinstance(box, list) and len(box) == 6
                  and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in box))
            if not ok or box[0] > box[3] or box[1] > box[4] or box[2] > box[5]:
                raise ValueError(f"{where}: box must be six numbers x0, y0, z0, x1, y1, z1 with x0 <= x1, "
                                 "y0 <= y1 and z0 <= z1")
        out.append({"kind": kind, "box": box, "reason": reason.strip(), "used": 0})
    return out


def _covers(exc, f):
    """Does this exception apply to this finding? A finding with a position needs a box that
    contains its x and y and overlaps its height; a part-level finding takes an entry without one."""
    if exc["kind"] != f["kind"]:
        return False
    if "x" not in f:
        return exc["box"] is None
    b = exc["box"]
    return (b is not None and b[0] <= f["x"] <= b[3] and b[1] <= f["y"] <= b[4]
            and f["z1"] >= b[2] and f["z0"] <= b[5])


def apply_exceptions(findings, exceptions):
    """Mark the findings an exception covers as waived. Only kinds that may be waived."""
    import limits as L
    for f in findings:
        if f["severity"] not in ("fail", "warn") or not L.KINDS[f["kind"]]["waivable"]:
            continue
        for exc in exceptions:
            if _covers(exc, f):
                f["waived_from"], f["severity"], f["reason"] = f["severity"], "waived", exc["reason"]
                exc["used"] += 1
                break


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _versions():
    import importlib.metadata as md
    out = {"python": platform.python_version()}
    for n in NEEDS:
        try:
            out[n] = md.version(n)
        except md.PackageNotFoundError:
            out[n] = "unknown"
    return out


def _finding_dict(f):
    import limits as L
    d = f.to_dict()
    k = L.KINDS[f.kind]
    d["severity"] = k["severity"]
    d["scaled"] = L.kind_is_scaled(f.kind)
    if d["scaled"] and d["severity"] == "fail":
        d["severity"] = "warn"       # a limit scaled from the tested setup is not a measured rule
    d["waivable"] = k["waivable"]
    d["limit"] = None if k["limit"] is None else L.value(k["limit"])
    return d


def inspect_part(path, exceptions_path=None, slicer="auto", slicer_path=None, orca_presets=None):
    """Everything known about one part, as the report dict. Never raises for a bad part.
    Exceptions are read from `exceptions_path`, or from <part>.exceptions.json if it exists."""
    import limits as L
    report = {
        "schema": REPORT_SCHEMA,
        "tool": {"name": "fdm-print-ready-models", "version": __version__},
        "generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "part": {"file": os.path.basename(path)},
        "setup": {"nozzle_mm": L.NOZZLE, "layer_mm": L.LAYER, "tested": L.tested()},
        "limits": {n: {"value": lim.value, "unit": lim.unit, "source": lim.source}
                   for n, lim in L.LIMITS.items()},
        "versions": _versions(),
        "checks": [], "part_error": None, "part_findings": [],
    }

    solid = None
    if not os.path.isfile(path):
        report["part_error"] = f"file not found: {os.path.basename(path)}"
    else:
        report["part"]["sha256"] = _sha256(path)
        import layers
        try:
            solid = layers.load(path)
        except layers.MeshError as e:
            report["part_error"] = f"mesh problem: {e}"
        except Exception as e:  # the STL reader raises many types; all mean "cannot read this"
            report["part_error"] = f"not a readable STL ({type(e).__name__}: {e})"

    if solid is not None:
        bb = solid.bounding_box()
        size = [round(bb[3] - bb[0], 2), round(bb[4] - bb[1], 2), round(bb[5] - bb[2], 2)]
        report["part"].update({"size_mm": size, "z_min": round(bb[2], 3),
                               "bodies": len(solid.decompose())})
        biggest = max(size)
        if biggest < L.MIN_PART_SIZE or biggest > L.MAX_PART_SIZE or size[2] < L.LAYER:
            report["part_error"] = (f"implausible size {size[0]} x {size[1]} x {size[2]} mm: "
                                    "check the export units (mm) and the orientation")
            solid = None
        else:
            if biggest < L.SMALL_PART_SIZE:
                report["part_findings"].append(
                    {"kind": "small_part", "value": biggest, "what": "size_mm", "severity": "warn",
                     "waivable": True, "limit": L.SMALL_PART_SIZE})
            if abs(bb[2]) > L.BED_TOL:
                report["part_findings"].append(
                    {"kind": "off_bed", "value": round(bb[2], 3), "what": "z_min_mm",
                     "severity": "warn", "waivable": True, "limit": 0.0})

    exceptions, exc_error = [], None
    exc_path = exceptions_path or os.path.splitext(path)[0] + ".exceptions.json"
    if exceptions_path or os.path.isfile(exc_path):
        try:
            exceptions = load_exceptions(exc_path)
        except ValueError as e:
            exc_error = f"exceptions file {os.path.basename(exc_path)}: {e}"
        report["exceptions"] = {"file": os.path.basename(exc_path), "entries": len(exceptions),
                                "error": exc_error}
    apply_exceptions(report["part_findings"], exceptions)

    ctx = {"path": path, "slicer": slicer, "slicer_path": slicer_path, "orca_presets": orca_presets,
           "slicer_info": {}}
    for c in CHECKS:
        entry = {"name": c["name"], "status": "not_shipped", "findings": [], "error": None}
        if c["run"] is not None and solid is None:
            entry["status"] = "error"
            entry["error"] = "not run: the part could not be read"
        elif c["run"] is not None:
            try:
                entry["findings"] = [_finding_dict(f) for f in c["run"](solid, ctx)]
                apply_exceptions(entry["findings"], exceptions)
                sev = {f["severity"] for f in entry["findings"]}
                entry["status"] = "fail" if "fail" in sev else "warn" if "warn" in sev else "pass"
            except Exception as e:  # one crashing check must not hide the others; it is reported
                if type(e).__name__ == "Skipped":       # no slicer, no presets, a package missing
                    entry["status"], entry["note"] = "skipped", str(e)
                elif type(e).__name__ == "SlicerError":
                    entry["status"], entry["error"] = "error", str(e)
                else:
                    entry["status"] = "error"
                    entry["error"] = traceback.format_exc()
        report["checks"].append(entry)

    if solid is not None:      # entries that could not or did not apply are shown, never dropped
        for exc in exceptions:
            if not L.KINDS[exc["kind"]]["waivable"]:
                report["part_findings"].append({"kind": "exception_refused", "what": "note", "severity": "warn",
                                                "waivable": False, "limit": None, "value": exc["kind"]})
            elif not exc["used"]:
                report["part_findings"].append({"kind": "exception_unused", "what": "note", "severity": "warn",
                                                "waivable": False, "limit": None,
                                                "value": f"{exc['kind']} ({exc['reason']})"})

    verdict, quals = decide(report["checks"], report["part_error"] or exc_error)
    every = report["part_findings"] + [f for c in report["checks"] for f in c["findings"]]
    counts = {s: sum(1 for f in every if f["severity"] == s) for s in ("fail", "warn", "info", "waived")}
    if counts["waived"]:
        quals.insert(0, f"with {counts['waived']} waiver{'s' if counts['waived'] != 1 else ''}")
    if counts["warn"]:
        quals.insert(0, f"with {counts['warn']} warning{'s' if counts['warn'] != 1 else ''}")
    ran = [c["name"] for c in report["checks"] if c["status"] in ("pass", "warn", "fail")]
    if not L.tested():
        quals.insert(0, f"{L.NOZZLE:g} mm nozzle and {L.LAYER:g} mm layers: scaled limits, not measured")
    if verdict == "PASS" and len(ran) < len(CHECKS):
        names = ran[0] if len(ran) == 1 else ", ".join(ran[:-1]) + " and " + ran[-1] if ran else ""
        quals.insert(0, f"{names} check{'s' if len(ran) > 1 else ''} only" if ran else "no check ran")
    if ctx["slicer_info"]:
        report["slicer"] = ctx["slicer_info"]
    report.update({"verdict": verdict, "qualifiers": quals, "counts": counts})
    return report


def _describe(f):
    import limits as L
    text = L.KINDS[f["kind"]]["text"]
    if f["what"] == "note":
        return f"{text}: {f['value']}"
    what = {"span_mm": "span {v} mm", "reach_mm": "sticks out {v} mm", "area_mm2": "area {v} mm2",
            "size_mm": "largest side {v} mm", "z_min_mm": "lowest point at z = {v} mm",
            "ratio": "{v} times as tall as wide", "angle_deg": "{v} degrees from the bed",
            "length_mm": "{v} mm long", "total_length_mm": "{v} mm in total"}[f["what"]]
    line = f"{text}: {what.format(v=f['value'])}"
    if f.get("width") and f["kind"] in ("bridge", "ceiling_bridge"):
        line += f", {f['width']} mm wide"
    elif f.get("width") and f["kind"].startswith("thin_post"):
        line += f", narrowest post {f['width']} mm"
    elif f.get("width") and f["kind"] == "slender_column":
        line += f", {f['width']} mm wide"
    elif f.get("width") and f["kind"] == "slope_too_shallow":
        line += f", about {f['width']} mm wide"
    elif f.get("width") and f["kind"].startswith("overhang_"):
        line += f", running out about {f['width']} mm"
    elif f.get("width") and f["kind"] == "slicer_wall_in_air":
        line += f", over a run of {f['width']} mm"
    elif f.get("width") and f["kind"].startswith("support_"):
        line += f", {f['width']} mm above the surface it would stand on"
    if f.get("limit") is not None and f["what"] in ("span_mm", "reach_mm"):
        line += f" (limit {f['limit']} mm)"
    if f.get("limit") is not None and f["what"] == "angle_deg":
        line += f" (limit {f['limit']:g}), {f['area']} mm2"
    if f["kind"] == "sharp_corner_vertical":
        return f"{text}: {int(f['area'])} of them, {f['value']} mm in total"
    if f.get("scaled"):
        line += f" [limit scaled from a {L.TESTED_NOZZLE} mm nozzle, not measured]"
    if "x" in f:
        z = f"{f['z0']}" if f["z0"] == f["z1"] else f"{f['z0']} to {f['z1']}"
        line += f"  at x {f['x']}, y {f['y']}, z {z}"
    return line


def format_text(report, verbose=False):
    lines = [report["part"]["file"]]
    if report["part_error"]:
        lines.append(f"  could not check this part: {report['part_error']}")
    every = report["part_findings"] + [f for c in report["checks"] for f in c["findings"]]
    for sev, label in (("fail", "FAIL"), ("warn", "warn")):
        for f in every:
            if f["severity"] == sev:
                lines.append(f"  {label}  {_describe(f)}")
    for f in every:
        if f["severity"] == "waived":
            lines.append(f"  waived  {_describe(f)}\n          reason: {f['reason']}")
    if report.get("exceptions", {}).get("error"):
        lines.append(f"  problem with the {report['exceptions']['error']}")
    info = [f for f in every if f["severity"] == "info"]
    if info and verbose:
        lines += [f"  info  {_describe(f)}" for f in info]
    elif info:
        import limits as L
        bridges = [f for f in info if f["kind"] == "bridge"]
        if bridges:
            longest = max(f["value"] for f in bridges)
            lines.append(f"  info  {len(bridges)} bridge{'s' if len(bridges) != 1 else ''} within limits "
                         f"(longest {longest} mm); --verbose lists them")
        for kind in dict.fromkeys(f["kind"] for f in info if f["kind"] != "bridge"):
            group = [f for f in info if f["kind"] == kind]
            if kind == "sharp_corner_vertical":
                lines.append(f"  info  {_describe(group[0])}")
            else:
                lines.append(f"  info  {len(group)} x {L.KINDS[kind]['text']}; --verbose lists them")
    for c in report["checks"]:
        if c["status"] == "skipped":
            lines.append(f"  the {c['name']} check did not run: {c.get('note', '')}")
    if report.get("slicer"):
        lines.append(f"  sliced with {report['slicer']['name']} {report['slicer']['version']}")
    for c in report["checks"]:
        if c["status"] == "error" and c["error"] and not report["part_error"]:
            lines.append(f"  the {c['name']} check crashed: {c['error'].strip().splitlines()[-1]}")
    tail = f" ({'; '.join(report['qualifiers'])})" if report["qualifiers"] else ""
    lines.append(f"VERDICT: {report['verdict']}{tail}")
    return "\n".join(lines)


def skill_tables():
    """The tables SKILL.md must contain, generated so the text cannot disagree with the code."""
    import limits as L
    L.use()       # the tables always describe the tested setup
    out = [BEGIN, "", "### Limits the checks use", "",
           f"For a {L.NOZZLE} mm nozzle and {L.LAYER} mm layers.", "",
           "| Limit | Value | Source | Meaning |", "|---|---|---|---|"]
    for name, lim in L.LIMITS.items():
        out.append(f"| `{name}` | {lim.value:g} {lim.unit} | {lim.source} | {lim.text} |")
    out += ["", "### What the checks report", "",
            "| Finding | Severity | Can be waived | Meaning |", "|---|---|---|---|"]
    for kind, k in L.KINDS.items():
        out.append(f"| `{kind}` | {k['severity']} | {'yes' if k['waivable'] else 'no'} | {k['text']} |")
    out += ["", f"### Checks in version {__version__}", "",
            "| Check | Runs in this version | What it looks at |", "|---|---|---|"]
    for c in CHECKS:
        out.append(f"| {c['name']} | {'yes' if c['run'] is not None else 'no, manual for now'} | {c['text']} |")
    out += ["", END]
    return "\n".join(out)


def update_skill_tables(skill_path):
    with open(skill_path) as fh:
        text = fh.read()
    block = skill_tables()
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n## Reference tables\n\n" + block + "\n"
    with open(skill_path, "w") as fh:
        fh.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Print-readiness checks for FDM parts (STL, print orientation, mm).")
    ap.add_argument("parts", nargs="*", help="STL files")
    ap.add_argument("--out", help="report path (one part only)")
    ap.add_argument("--no-report", action="store_true", help="do not write report files")
    ap.add_argument("--verbose", action="store_true", help="list findings that are information only")
    ap.add_argument("--exceptions", help="exceptions file (one part only; default <part>.exceptions.json)")
    ap.add_argument("--slicer", choices=("auto", "prusa", "orca", "none"), default="auto",
                    help="which slicer the slicer check uses (default: PrusaSlicer if installed)")
    ap.add_argument("--slicer-path", help="path to the slicer program, if it is not found by name")
    ap.add_argument("--orca-presets", nargs=3, metavar=("MACHINE", "PROCESS", "FILAMENT"),
                    help="three preset files exported from OrcaSlicer; needed to use it")
    ap.add_argument("--nozzle", type=float, default=None, help="nozzle width in mm (tested: 0.4)")
    ap.add_argument("--layer", type=float, default=None, help="layer height in mm (tested: 0.2)")
    ap.add_argument("--skill-tables", action="store_true", help="print the tables for SKILL.md")
    ap.add_argument("--update-skill-tables", action="store_true", help="rewrite the tables in ../SKILL.md")
    ap.add_argument("--version", action="version", version=__version__)
    args = ap.parse_args(argv)

    if args.skill_tables:
        print(skill_tables())
        return 0
    if args.update_skill_tables:
        update_skill_tables(os.path.join(os.path.dirname(HERE), "SKILL.md"))
        return 0
    if not args.parts:
        ap.print_usage(sys.stderr)
        return 2
    if args.out and len(args.parts) > 1:
        print("--out takes one part; without it each part gets <part>.report.json", file=sys.stderr)
        return 2
    if args.exceptions and len(args.parts) > 1:
        print("--exceptions takes one part; without it each part uses <part>.exceptions.json", file=sys.stderr)
        return 2
    missing = missing_packages()
    if missing:
        print(install_help(missing), file=sys.stderr)
        return 2
    import limits as L
    nozzle = L.TESTED_NOZZLE if args.nozzle is None else args.nozzle
    layer = L.TESTED_LAYER if args.layer is None else args.layer
    if not (0.1 <= nozzle <= 2.0 and 0.04 <= layer <= nozzle):
        print("--nozzle must be 0.1 to 2.0 mm and --layer 0.04 mm up to the nozzle width", file=sys.stderr)
        return 2
    L.use(nozzle, layer)

    verdicts = []
    for i, path in enumerate(args.parts):
        report = inspect_part(path, args.exceptions, args.slicer, args.slicer_path, args.orca_presets)
        verdicts.append(report["verdict"])
        if i:
            print()
        print(format_text(report, args.verbose))
        if not args.no_report:
            out = args.out or os.path.splitext(path)[0] + ".report.json"
            try:
                with open(out, "w") as fh:
                    json.dump(report, fh, indent=1)
                print(f"report: {out}")
            except OSError as e:
                print(f"warning: could not write the report ({e})", file=sys.stderr)
    return 1 if "FAIL" in verdicts else 2 if "INCOMPLETE" in verdicts else 0


